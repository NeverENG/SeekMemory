@runtime_checkable
class ChatModel(Protocol):
    async def complete(self, request: ChatRequest) -> ChatResponse: ...


@runtime_checkable
class HistoryReader(Protocol):
    """Read metadata and ordered messages from a supported history file."""

    def inspect(self, path: str | Path) -> HistoryInspection: ...
    def iter_messages(self, path: str | Path) -> Iterator[HistoryMessage]: ...
    def iter_messages_sorted(self, path: str | Path) -> Iterator[HistoryMessage]: ...


@runtime_checkable
class Retriever(Protocol):
    def retrieve(self, query: str, pool: list[Artifact]) -> list[RetrievalCandidate]: ...


@runtime_checkable
class SourceStore(Protocol):
    def append_sources(self, sources: list[Source]) -> int: ...
    def recent_sources(self, *, since: str, limit: int) -> list[Source]: ...
    def source_umo(self, source_id: str) -> str: ...
    def source_umos(self, source_ids: list[str]) -> dict[str, str]: ...
    def sources_by_ids(self, source_ids: list[str]) -> dict[str, Source]: ...


@runtime_checkable
class ArtifactStore(Protocol):
    def commit(self, art: Artifact, *, expected_revision: int, op: str,
               reason: str = "", source_ids: tuple[str, ...] = (),
               state_events: tuple[StateEvent, ...] = ()) -> None: ...
    def commit_many(
        self,
        writes: list[tuple[Artifact, int, tuple[str, ...]]],
        *,
        op: str,
        reason: str = "",
    ) -> None: ...
    def get(self, node_id: str) -> Artifact | None: ...
    def by_source_ids(self, source_ids: list[str]) -> list[Artifact]: ...
    def list(self, family: str | None = None,
             state: str | None = None) -> list[Artifact]: ...
    def history(self, node_id: str) -> list[dict]: ...
    def add_edge(self, src: str, dst: str, kind: str, weight: float) -> None: ...
    def edges_of(self, node_id: str) -> list[tuple[str, str, float]]: ...
    def set_parent(self, node_id: str, parent_id: str | None) -> None: ...
    def inspect_record(self, node_id: str) -> dict: ...


@runtime_checkable
class ArtifactCache(Protocol):
    artifacts: ArtifactStore

    @property
    def version(self) -> int: ...
    def load(self) -> None: ...
    def put(self, art: Artifact) -> None: ...
    def get(self, node_id: str) -> Artifact | None: ...
    def active(self, family: str | None = None) -> list[Artifact]: ...
    def by_level(self, level: str) -> list[Artifact]: ...
    def by_subject(self, subject_id: str) -> list[Artifact]: ...
    def remove(self, node_id: str) -> None: ...
    def size(self) -> int: ...


@runtime_checkable
class MetricsStore(Protocol):
    def capacity_usage(self, now: str = "") -> dict[str, Any]: ...


@runtime_checkable
class LedgerStore(Protocol):
    def entries(self) -> list[Any]: ...
    def verify(self) -> bool: ...


@runtime_checkable
class ExtractionStore(Protocol):
    def enqueue_extraction(
        self,
        source: Source,
        topic_id: str,
        created_at: str = "",
        *,
        deferred: bool = False,
    ) -> bool: ...
    def pending_extractions(self, now: str = "") -> list[dict]: ...
    def queue_counts(self) -> dict[str, int]: ...
    def release_deferred(self, limit: int = 50) -> int: ...
    def ready_extraction_ids(self, now: str = "") -> set[str]: ...
    def mark_extraction_succeeded(self, source_ids: list[str]) -> int: ...
    def mark_extraction_failed(
        self,
        source_ids: list[str],
        error_type: str,
        *,
        max_attempts: int = 5,
        now: str = "",
    ) -> int: ...


@runtime_checkable
class HistoryImportStore(Protocol):
    """Persistent lifecycle and task-scoped Source extraction projection."""

    def create_task(self, task_id: str, stage_key: str, *, format_id: str = "chatlab",
                    duplicate_count: int = 0, skipped_count: int = 0,
                    selection: dict[str, str] | None = None,
                    at: str = "") -> None: ...
    def recover_interrupted(self, at: str = "") -> int: ...
    def set_status(self, task_id: str, status: str, at: str = "") -> bool: ...
    def task(self, task_id: str) -> dict[str, Any] | None: ...
    def task_stage(self, task_id: str) -> dict[str, str] | None: ...
    def task_selection(self, task_id: str) -> dict[str, str] | None: ...
    def release_stage(self, task_id: str) -> bool: ...
    def supersede_interrupted(self, old_task_id: str, new_task_id: str) -> int: ...
    def list_tasks(self, limit: int = 50) -> list[dict[str, Any]]: ...
    def retained_stage_keys(self, *, now: str) -> set[str]: ...
    def clear_preflight(self, stage_key: str) -> int: ...
    def preflight_user_topics(
        self, stage_key: str, source_ids: list[str]
    ) -> dict[str, str]: ...
    def validate_sources(self, stage_key: str,
                         entries: list[SourceQueueEntry]) -> dict[str, int]: ...
    def admit_sources(self, task_id: str, entries: list[SourceQueueEntry],
                       *, stage_key: str = "") -> int: ...
    def topic_ids(self, task_id: str, *, after_topic_id: str = "",
                  limit: int = 500) -> list[str]: ...
    def next_ready_topic(self, task_id: str, *, now: str) -> str: ...
    def topic_sources(self, task_id: str, topic_id: str, *, limit: int = 121,
                      now: str = "") -> list[dict[str, Any]]: ...
    def counts(self, task_id: str) -> dict[str, int]: ...
    def next_attempt_at(self, task_id: str) -> str: ...
    def finish_task(self, task_id: str, status: str, *, persona_status: str,
                    error_types: list[str] | None = None, retain_stage: bool = False,
                    at: str = "") -> dict[str, int]: ...
    def abandon_task(self, task_id: str, at: str = "") -> bool: ...
    def prune(self, *, now: str, retention_days: int = 30) -> int: ...


@runtime_checkable
class HistoryImportFiles(Protocol):
    """Private staged files consumed only by the history import workflow."""

    def preview_path(self, key: str) -> Path: ...
    def path_for_key(self, key: str) -> Path: ...
    def release_preview(self, key: str) -> None: ...
    def delete(self, key: str) -> None: ...
    def cleanup(self, *, retained_keys: set[str], now: datetime | None = None) -> int: ...
